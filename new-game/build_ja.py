def build():
    s = open(SRC, encoding='utf-8').read()
    keys = sorted(JA, key=len, reverse=True)
    pat = re.compile('(?<![가-힣])(' + '|'.join(re.escape(k) for k in keys) + ')(?![가-힣])')
    out = pat.sub(lambda m: JA[m.group(1)], s)
    # 한국어 받침 도우미(을/를) → 일본어는 항상 'を'
    out = re.sub(r"const eul = \(w\) => \{[^\n]*\};", "const eul = (w) => w + 'を';", out)
    # 언어 · 글꼴: 한국어 글꼴(Jua · Black Han Sans)에는 일본어 글자가 없어서 일본어 글꼴로
    out = out.replace('<html lang="ko">', '<html lang="ja">')
    out = out.replace('family=Black+Han+Sans&family=Jua&display=swap', 'family=Dela+Gothic+One&family=M+PLUS+Rounded+1c:wght@500;800&display=swap')
    out = re.sub(r'--f-display:[^;]*;', '--f-display:"Dela Gothic One","Hiragino Sans","Yu Gothic",sans-serif;', out)
    out = re.sub(r'--f-ui:[^;]*;', '--f-ui:"M PLUS Rounded 1c","Hiragino Maru Gothic ProN","Yu Gothic",sans-serif;', out)
    out = re.sub(r"const UIF = '[^']*';", "const UIF = '\"M PLUS Rounded 1c\",\"Hiragino Maru Gothic ProN\",sans-serif';", out)
    out = out.replace("document.fonts.load('12px Jua')", "document.fonts.load('12px \"M PLUS Rounded 1c\"')")
    out = out.replace("'yj2.", "'yj2ja.")
    out = out.replace("const BUILD_LANG = 'ko';", "const BUILD_LANG = 'ja';")
    out = out.replace('🌐 日本語', '🌐 한국어')
    out = out.replace('</style>', '.title{font-size:clamp(38px,11.5vw,50px)}\n</style>', 1)   # 'ディフェンス'가 한 줄에 들어가게                     # 저장 칸을 한국판과 따로
    open(OUT, 'w', encoding='utf-8').write(out)
    # 코드 · 화면 글자에 남은 한국어 (주석은 빼고) 알려 주기
    code = re.sub(r'/\*.*?\*/|<!--.*?-->', '', out, flags=re.S)
    left = set()
    for line in code.split('\n'):
        line = re.sub(r'(?<![:\'"\\])//.*$', '', line)
        for m in re.finditer(r'[가-힣][가-힣 ]*', line):
            if m.group(0) not in ('가-힣',): left.add(m.group(0).strip())
    left -= {'가', '힣', '한국어'}
    if left: print('번역 없음:', sorted(left))
    print('만들었어요:', OUT)
    # 🌐 한·일 합친 페이지: 한국판 + 일본판 통째로 → 일본어를 고르면 페이지를 일본판으로 바꿔 써요 (같은 랭킹 · 같은 접속 서버)
    import json
